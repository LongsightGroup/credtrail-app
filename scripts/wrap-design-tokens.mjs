import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname } from "node:path";

const cssPath = "apps/api-worker/src/ui/page-assets/content/generated/design-tokens.css";
const tsPath = "apps/api-worker/src/ui/page-assets/content/generated/design-tokens-css.ts";

const escapeTemplateLiteral = (value) => {
  return value.replaceAll("\\", "\\\\").replaceAll("`", "\\`").replaceAll("${", "\\${");
};

const css = await readFile(cssPath, "utf8");
const ts = `// Generated by pnpm build:design-tokens. Do not edit manually.
export const GENERATED_DESIGN_TOKENS_CSS = \`
${escapeTemplateLiteral(css.trim())}
\`;
`;

await mkdir(dirname(tsPath), { recursive: true });
await writeFile(tsPath, ts);
